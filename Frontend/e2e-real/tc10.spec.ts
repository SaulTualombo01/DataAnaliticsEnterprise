const rootEmail=process.env.TC10_ROOT_EMAIL!,rootPassword=process.env.TC10_ROOT_PASSWORD!,password=process.env.TC10_TEST_PASSWORD!;
async function login(page:Page,email:string,pw=password) {
  await page.bringToFront();
  await page.goto('/');
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña',{exact:true}).fill(pw);
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Tus proyectos',exact:true})).toBeVisible();
}
async function reason(page:Page,text:string) { await page.getByRole('dialog').getByLabel('Motivo del cambio').fill(text); }
async function invite(page:Page,name:string,email:string) {
  await page.bringToFront();
  await page.getByRole('button',{name:'Invitaciones',exact:true}).click();
  await page.getByRole('button',{name:'Invitar empleado',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nombre del empleado').fill(name);
  await dialog.getByLabel('Correo del empleado').fill(email);
  await reason(page,'Invitación sintética del recorrido TC-10');
  await dialog.getByRole('button',{name:'Crear invitación',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Invitación creada',exact:true})).toBeVisible();
  const token=await page.getByLabel('Código de activación').inputValue();
  await page.getByRole('button',{name:'Cerrar recibo'}).click();
  await expect(page.getByLabel('Código de activación')).toHaveCount(0);
  return token;
}
async function activate(page:Page,token:string) {
  await page.bringToFront();
  await page.goto('/');
  await page.getByRole('button',{name:'Tengo una invitación'}).click();
  await page.getByLabel('Código de invitación').fill(token);
  await page.getByLabel('Nueva contraseña',{exact:true}).fill(password);
  await page.getByLabel('Repite la nueva contraseña').fill(password);
  await page.getByRole('button',{name:'Activar cuenta',exact:true}).click();
  await expect(page.getByText(/Cuenta activada/)).toBeVisible();
  await expect(page.getByLabel('Código de invitación')).toHaveCount(0);
}
async function assignRole(page:Page) {
  await page.bringToFront();
  await page.getByRole('button',{name:'Configurar rol',exact:true}).click();
  await page.getByRole('combobox',{name:'Rol funcional',exact:true}).selectOption('GESTOR_CATALOGO');
  await page.getByLabel('Todo el proyecto',{exact:true}).check();
  await reason(page,'Función y alcance explícitos de la prueba');
  await page.getByRole('button',{name:'Asignar rol',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
}
